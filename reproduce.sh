#!/usr/bin/env bash
set -euo pipefail
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export PYTHONPATH="$REPO_ROOT/src${PYTHONPATH:+:$PYTHONPATH}"

usage() {
  cat <<'EOF'
Portable reproduction entrypoint

Usage:
  bash reproduce.sh experiment [arguments passed to: python -m e1_tdim_msb.cli]
  bash reproduce.sh chronology [arguments passed to chronology repair script]
  bash reproduce.sh analysis [arguments passed to final analysis script]
  bash reproduce.sh relationship --class-block PATH --out DIR [--bootstrap-reps N] [--bootstrap-seed N]

Portable environment roots recognized by path-sanitized public scripts:
  E1_PROJECT_ROOT   working E1 project/output root
  E1_DATA_ROOT      directory containing benchmark dataset files

Examples:
  bash reproduce.sh experiment --help
  bash reproduce.sh chronology --help
  bash reproduce.sh analysis --help
  bash reproduce.sh relationship \
      --class-block /path/to/nonoverlap_block_class_metrics_derived.parquet \
      --out ./relationship_results

The benchmark datasets and the derived class-block parquet are intentionally
not included in this repository. The class-block parquet is regenerated by the
final analysis pipeline before relationship analysis.
EOF
}

cmd="${1:-help}"
case "$cmd" in
  help|-h|--help)
    usage
    ;;
  experiment)
    shift
    exec python -m e1_tdim_msb.cli "$@"
    ;;
  chronology)
    shift
    exec python "$REPO_ROOT/chronology/authoritative/e1_repair_cse_temporal_v1_1.py" "$@"
    ;;
  analysis)
    shift
    exec python "$REPO_ROOT/analysis/e1_final_analysis_v1_0.py" "$@"
    ;;
  relationship)
    shift
    CLASS_BLOCK=""
    OUT=""
    REPS="5000"
    SEED="20260831"
    while [[ $# -gt 0 ]]; do
      case "$1" in
        --class-block) CLASS_BLOCK="$2"; shift 2 ;;
        --out) OUT="$2"; shift 2 ;;
        --bootstrap-reps) REPS="$2"; shift 2 ;;
        --bootstrap-seed) SEED="$2"; shift 2 ;;
        -h|--help)
          usage; exit 0 ;;
        *) echo "Unknown relationship argument: $1" >&2; exit 2 ;;
      esac
    done
    [[ -n "$CLASS_BLOCK" ]] || { echo "--class-block is required" >&2; exit 2; }
    [[ -f "$CLASS_BLOCK" ]] || { echo "Class-block input not found: $CLASS_BLOCK" >&2; exit 2; }
    [[ -n "$OUT" ]] || { echo "--out is required" >&2; exit 2; }
    exec python "$REPO_ROOT/analysis/relationship_v1_1/run_e1_rq1_formal_relationship_analysis.py" \
      --block-class-source "$CLASS_BLOCK" \
      --out "$OUT" \
      --bootstrap-reps "$REPS" \
      --bootstrap-seed "$SEED"
    ;;
  *)
    echo "Unknown command: $cmd" >&2
    usage >&2
    exit 2
    ;;
esac
